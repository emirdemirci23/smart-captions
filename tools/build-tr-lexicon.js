#!/usr/bin/env node
/*
 * Builds js/data/tr-lexicon.js from Zemberek's master dictionary
 * (https://github.com/ahmetaa/zemberek-nlp, Apache License 2.0).
 *
 *   node tools/build-tr-lexicon.js path/to/master-dictionary.dict
 *
 * Keeps only what caption phrasing needs: adjectives, adverbs, conjunctions,
 * postpositions, determiners, pronouns and verb roots.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) { console.error('usage: node tools/build-tr-lexicon.js master-dictionary.dict'); process.exit(1); }
const lines = fs.readFileSync(src, 'utf8').split(/\r?\n/);
const groups = { adj: new Set(), adv: new Set(), conj: new Set(), postp: new Set(), det: new Set(), pron: new Set(), verb: new Set() };
const lower = (w) => w.replace(/İ/g, 'i').replace(/I/g, 'ı').toLowerCase();

for (const line of lines) {
  const m = /^(\S+)(?:\s+\[([^\]]*)\])?\s*$/.exec(line.trim());
  if (!m) continue;
  const word = lower(m[1]);
  if (!/^[a-zçğıöşüâîû]+$/.test(word)) continue;          // single words only
  const pos = (/P:([A-Za-z]+)/.exec(m[2] || '') || [])[1];
  if (!pos) {
    if (/(mak|mek)$/.test(word) && word.length > 4) groups.verb.add(word.slice(0, -3));
    continue;
  }
  const g = { Adj: 'adj', Adv: 'adv', Conj: 'conj', Postp: 'postp', Det: 'det', Pron: 'pron' }[pos];
  if (g) groups[g].add(word);
}

const out = {};
for (const [k, v] of Object.entries(groups)) out[k] = [...v].sort().join(' ');
const file = `/*! Turkish word lists derived from the Zemberek-NLP master dictionary
 * (c) 2018 Ahmet A. Akın, Mehmet D. Akın – Apache License 2.0
 * https://github.com/ahmetaa/zemberek-nlp  (see js/data/zemberek.LICENSE.txt)
 * Generated by tools/build-tr-lexicon.js – do not edit by hand.
 */
(function (root, data) {
  if (typeof module === 'object' && module.exports) module.exports = data;
  else root.SmartTRLexicon = data;
}(typeof self !== 'undefined' ? self : this, ${JSON.stringify(out)}));
`;
fs.writeFileSync(path.join(__dirname, '..', 'js', 'data', 'tr-lexicon.js'), file);
console.log(Object.entries(groups).map(([k, v]) => `${k} ${v.size}`).join(', '), `| ${(file.length / 1024).toFixed(0)} KB`);
